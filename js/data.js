/** แปลงอาร์เรย์เป็นอ็อบเจกต์อ่านง่าย */
export const asTip = ([icon, title, summary, detail, source]) =>
  ({ icon, title, summary, detail, source });

/** เคล็ดลับประจำวัน หมุนเวียนรายวันภายในช่วงนั้น (สูตรเดียวกับแอป Flutter) */
export function tipOfDay(phase, dayISO) {
  const list = phase ? tipsByPhase[phase] : generalTips;
  const days = Math.floor((new Date(`${dayISO}T12:00:00`) - new Date(2020, 0, 1, 12)) / 86400000);
  return asTip(list[((days % list.length) + list.length) % list.length]);
}
